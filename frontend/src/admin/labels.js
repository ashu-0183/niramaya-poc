const humanize = (key) =>
  key
    .replace(/T$/, " heading")
    .replace(/Ph$/, " placeholder")
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/^./, (c) => c.toUpperCase());

export const labelFor = (path) => {
  const key = String(path[path.length - 1]);
  const parent = String(path[path.length - 2] ?? "");
  return MAP[`${parent}.${key}`] ?? MAP[key] ?? humanize(key);
};

